#!/usr/bin/env bun
// Generates model-hint modules from the committed snapshot (ADR-0028).
// --refresh first fetches models.dev and updates that snapshot; normal generation
// is deterministic and offline. Codex hints stay hand-maintained in the provider.
import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { Result, Schema } from "effect";
import { knownModelIds as codexIds } from "../packages/providers/src/openai-codex/models.ts";
import { catalogUrl, toolCapableOpenAiModels } from "../packages/cli/src/catalog.ts";
import type { OpenAiCatalogModel } from "../packages/cli/src/catalog.ts";

const root = fileURLToPath(new URL("..", import.meta.url));
const snapshotPath = join(root, "scripts", "models-dev.snapshot.json");
const openAiHintsPath = join(root, "packages", "providers", "src", "openai", "models.ts");
const createMitomeHintsPath = join(root, "packages", "create-mitome", "src", "model-hints.ts");

const NonEmptyString = Schema.String.check(Schema.isNonEmpty());
// contextWindow is absent, never guessed, when models.dev reports no usable limit.context.
const SnapshotModel = Schema.Struct({
  id: NonEmptyString,
  contextWindow: Schema.optional(Schema.Int.check(Schema.isGreaterThan(0))),
});
const ModelSnapshotFromJson = Schema.fromJsonString(
  Schema.Struct({ openai: Schema.NonEmptyArray(SnapshotModel) }),
);

const fetchOpenAiModels = async (): Promise<Array<OpenAiCatalogModel>> => {
  const response = await fetch(catalogUrl, {
    signal: AbortSignal.timeout(10_000),
  });
  if (!response.ok) throw new Error(`models.dev returned ${response.status}`);
  const models = toolCapableOpenAiModels(await response.json());
  if (models.length === 0) throw new Error("models.dev returned no tool-capable OpenAI models");
  // Descending sort keeps newest model generations first and diffs deterministic.
  return models.sort((left, right) => (left.id < right.id ? 1 : -1));
};

const snapshotOpenAiModels = async (): Promise<ReadonlyArray<typeof SnapshotModel.Type>> => {
  const snapshot = Schema.decodeResult(ModelSnapshotFromJson)(await readFile(snapshotPath, "utf8"));
  if (Result.isFailure(snapshot)) {
    throw new Error(`Snapshot ${snapshotPath} holds no OpenAI models: ${snapshot.failure.message}`);
  }
  return snapshot.success.openai;
};

const args = process.argv.slice(2);
if (args.length > 1 || (args.length === 1 && args[0] !== "--refresh")) {
  throw new Error("Usage: generate-model-hints.ts [--refresh]");
}

const openAiModels =
  args[0] === "--refresh"
    ? await fetchOpenAiModels().then(async (models) => {
        // JSON.stringify drops undefined contextWindow, so absent limits stay absent.
        await writeFile(snapshotPath, `${JSON.stringify({ openai: models }, null, 2)}\n`);
        return models;
      })
    : await snapshotOpenAiModels();
const openAiIds = openAiModels.map((model) => model.id);

const header = "// Generated by scripts/generate-model-hints.ts — do not edit.";
const items = (ids: ReadonlyArray<string>, indent: string): string =>
  ids.map((id) => `${indent}"${id}",`).join("\n");
const metadataItems = openAiModels
  .flatMap((model) =>
    model.contextWindow === undefined
      ? []
      : [`  "${model.id}": { contextWindow: ${model.contextWindow} },`],
  )
  .join("\n");

await writeFile(
  openAiHintsPath,
  `${header}
import type { ModelMetadataMap } from "@mitome/core";

/** Tool-capable OpenAI Model ids from models.dev, offered as completions; not a closed catalog. */
export const knownModelIds = [
${items(openAiIds, "  ")}
] as const;

/** One id from \`knownModelIds\`. */
export type KnownModelId = (typeof knownModelIds)[number];

/** Context windows models.dev reports for \`knownModelIds\`; ids it omits stay unknown. */
export const knownModelMetadata: ModelMetadataMap = {
${metadataItems}
};
`,
);

await writeFile(
  createMitomeHintsPath,
  `${header}
export const knownModelIds: {
  readonly openai: ReadonlyArray<string>;
  readonly "openai-codex": ReadonlyArray<string>;
} = {
  openai: [
${items(openAiIds, "    ")}
  ],
  "openai-codex": [
${items(codexIds, "    ")}
  ],
};
`,
);

console.log(`Generated model hints: ${openAiIds.length} OpenAI ids, ${codexIds.length} Codex ids.`);
